tier = [[round(T_D - LEAD, 3), "D"], [round(T_C - LEAD, 3), "C"], [round(T_B - LEAD, 3), "B"], [round(T_A - LEAD, 3), "A"], [round(T_S - LEAD, 3), "S"], [round(T_X - LEAD, 3), None]]

# звук: смена сцены — whoosh; появления — pop; заставки уровней и штамп — удар; деньги — монетка
sfx = {"whoosh": [], "pop": [], "impact": [], "coin": [], "tick": []}
for s in scenes[1:]:
    (sfx["impact"] if s["type"] in ("tier",) else sfx["whoosh"]).append(s["t0"])
for s in scenes:
    for a in s.get("at") or []:
        if a is not None and a > s["t0"] + .2: sfx["pop"].append(a)
    for w in s.get("words") or []:
        if w["at"] > s["t0"] + .2: sfx["pop"].append(w["at"])
    if s["type"] == "warn" and s.get("stampAt"): sfx["impact"].append(s["stampAt"])
    if s["type"] == "number": sfx["coin"].append(s["t0"] + 1.0)
    if s["type"] == "offer": sfx["coin"].append(s["t0"] + .35)
    if s["type"] == "calc": sfx["coin"] += [s["totalAt"]]
music = [{"t": 0, "part": "intro"}, {"t": T_D - LEAD, "part": "main"}, {"t": T_X - LEAD, "part": "break"},
         {"t": T_CALC - LEAD, "part": "main"}]
TL = {"duration": dur, "fps": 30, "bpm": 96, "tier": tier, "scenes": scenes, "sfx": sfx, "music": music}
