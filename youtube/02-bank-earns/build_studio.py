W = Words(os.environ.get("WORDS") or os.path.join(DIR, "out", "words_final.json"))
BASE = [0]


def _hit(phrase, frm):
    W.cur = frm
    i, j = W._find(phrase)
    return i, j


def T(phrase):
    """Начало сцены: ищем дальше всего, что уже найдено; от этого слова ищутся якоря внутри сцены."""
    i, j = _hit(phrase, MAXC[0]); BASE[0] = i; MAXC[0] = max(MAXC[0], i + 1)
    return round(W.ws[i]["a"], 3)


def A(phrase):
    """Якорь внутри сцены: ищем от начала сцены (одна фраза может быть якорем и итога, и строки)."""
    i, j = _hit(phrase, BASE[0]); MAXC[0] = max(MAXC[0], i + 1)
    return round(W.ws[i]["a"], 3)


def E(phrase):
    i, j = _hit(phrase, BASE[0]); MAXC[0] = max(MAXC[0], j + 1)
    return round(W.ws[j]["a"] + W.ws[j]["d"], 3)


MAXC = [0]
SC, CH = [], []          # сцены; главы для описания


def match_words(words, i0):
    """Время каждого показанного слова — по слову голоса (поиск вперёд от i0), иначе +0,12 с от предыдущего."""
    out, j, t = [], i0, W.ws[i0]["a"]
    for w in words:
        shown, want = (w.split("@") + [None])[:2]
        key = norm(want or shown.strip("*^"))
        hit = None
        if key:
            for k in range(j, min(j + 9, len(W.ws))):
                tok = W.toks[k]
                if tok == key or (len(key) >= 3 and tok.startswith(key[:4])) or (key.isdigit() and tok.startswith(key)):
                    hit = k; break
        if hit is not None:
            t, j = W.ws[hit]["a"], hit + 1
        else:
            t = t + .12
        out.append((shown, round(t, 3)))
    return out


def scene(t0, **s):
    s["t0"] = round(t0 - .1, 3)
    if SC and s["t0"] < SC[-1]["t0"] + .7:   # после сжатия пауз якоря сблизились: даём предыдущей сцене ≥ 0,7 с
        assert s["t0"] > SC[-1]["t0"] - .05, f"сцена {s['type']} на {t0} раньше предыдущей"
        s["t0"] = round(SC[-1]["t0"] + .7, 3)
    SC.append(s); return s


def kin(anchor, text, acc="g", size=150, align="", sub=None, push=1.06, inner=False):
    """inner=True — якорь внутри предыдущей сцены (ищем от её начала, а не после всех её якорей)."""
    if inner:
        i, _ = _hit(anchor, BASE[0]); BASE[0] = i; MAXC[0] = max(MAXC[0], i + 1); t = round(W.ws[i]["a"], 3)
    else:
        t = T(anchor)
    i0 = BASE[0]
    flat = [w for ln in text.split("|") for w in ln.split()]
    times = iter(match_words(flat, i0))
    lines = []
    for ln in text.split("|"):
        row = []
        for _ in ln.split():
            shown, at = next(times)
            d = {"w": re.sub(r"[*^]", "", shown), "at": at}
            if "*" in shown: d["c"] = acc
            if "^" in shown: d["big"] = 1.3; d["c"] = d.get("c", acc)
            row.append(d)
        lines.append(row)
    s = scene(t, type="kinetic", acc=acc, size=size, align=align, push=push, lines=lines)
    if sub: s["sub"] = {"t": sub[1], "at": A(sub[0])}
    return s


def chapter(anchor, n, title, c, kicker="способ"):
    t = T(anchor)
    CH.append((t, f"Способ {n} — {title}" if n else title))
    return scene(t, type="card", acc=c, c=c, n=str(n) if n else "", kicker=kicker, title=title, titleAt=round(t + .15, 3), push=1.05, brand="BANK")


