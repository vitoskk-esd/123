ADJ = ("ый", "ий", "ой", "ая", "ое", "ые")


def main(path):
    rows = json.load(open(path, encoding="utf-8"))
    import yaml
    known = {}                             # город уже есть в cars.yaml (алиас региона) — оставляем регион оттуда («Ростов» — это Ростов-на-Дону)
    for rid, r in (yaml.safe_load(open("cars.yaml", encoding="utf-8"))["regions"]).items():
        for a in r.get("aliases") or []:
            known[str(a).lower().replace("ё", "е")] = rid
    by_name = defaultdict(list)
    for r in rows:
        if r["subject"] in SUBJECT:
            by_name[r["name"]].append((r.get("population") or 0, SUBJECT[r["subject"]]))
    out = defaultdict(list)
    for name, opts in sorted(by_name.items()):
        low = name.lower()
        if low in STOP or (" " not in low and "-" not in low and low.endswith(ADJ)):
            continue
        opts.sort(reverse=True)
        if known.get(low.replace("ё", "е"), opts[0][1]) != opts[0][1]:
            continue
        if len({rid for _, rid in opts}) > 1 and opts[0][0] < 5 * opts[1][0]:
            continue                       # одноимённые города разных регионов сравнимого размера (Заречный, Железногорск) — не угадываем
        out[opts[0][1]].append(name)
    print("# Города России → регион бота (tools/gen_cities.py; источник — github.com/pensnarik/russian-cities). Название — как пишут в объявлениях;")
    print("# падежи бот склоняет сам. Обычные слова и фамилии («Зима», «Дно», «Светлый», «Артём», «Гагарин») исключены.")
    for rid in sorted(out):
        print(f"{rid}: [{', '.join(sorted(out[rid]))}]")


